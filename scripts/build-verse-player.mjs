import { readFile, writeFile } from 'node:fs/promises';

const sources = [
  'js/profile-store.js',
  'js/profile-ui.js',
  'js/master-data.js',
  'js/audio-player.js',
  'js/renderers/gita-700.js',
  'js/renderers/registry.js',
  'js/editor.js',
  'js/player-core.js'
];

const parts = [];
for (const source of sources) {
  let code = await readFile(source, 'utf8');
  code = code
    .replace(/^import\s+[^;]+;\s*$/gm, '')
    .replace(/^export\s+(?=(const|class|function|async\s+function)\b)/gm, '');
  parts.push('// Source: ' + source + '\n' + code.trim());
}

const banner = [
  '/* Generated by scripts/build-verse-player.mjs.',
  ' * Edit the modular source files under js/, then rebuild this file.',
  ' * The classic bundle preserves direct file:// loading support.',
  ' */',
  '(() => {',
  "'use strict';"
].join('\n');

await writeFile('js/verse-player.bundle.js', banner + '\n\n' + parts.join('\n\n') + '\n\n})();\n');
